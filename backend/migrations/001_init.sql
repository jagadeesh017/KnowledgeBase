CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collection TEXT NOT NULL,
    tenant_id TEXT NOT NULL DEFAULT '',
    document_id TEXT NOT NULL,
    chunk_id TEXT NOT NULL UNIQUE,
    ingest_version TEXT NOT NULL,
    content TEXT NOT NULL,
    page_number INTEGER NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    embedding vector NOT NULL
);

CREATE INDEX IF NOT EXISTS document_chunks_lookup_idx
    ON document_chunks (collection, tenant_id, document_id);

CREATE INDEX IF NOT EXISTS document_chunks_metadata_idx
    ON document_chunks USING gin (metadata);

CREATE INDEX IF NOT EXISTS document_chunks_embedding_idx
    ON document_chunks USING hnsw (embedding vector_cosine_ops);

CREATE TABLE IF NOT EXISTS ingestion_jobs (
    id UUID PRIMARY KEY,
    tenant_id TEXT NOT NULL DEFAULT '',
    document_id TEXT NOT NULL,
    filename TEXT NOT NULL,
    source BYTEA NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'processing', 'succeeded', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0,
    max_attempts INTEGER NOT NULL DEFAULT 3,
    run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at TIMESTAMPTZ,
    locked_by TEXT,
    error TEXT,
    chunk_count INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ingestion_jobs_claim_idx
    ON ingestion_jobs (status, run_at, created_at);

CREATE INDEX IF NOT EXISTS ingestion_jobs_tenant_idx
    ON ingestion_jobs (tenant_id, created_at DESC);
